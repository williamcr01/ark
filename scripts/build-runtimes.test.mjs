import assert from 'node:assert/strict'
import { mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test from 'node:test'

import { ESBUILD_OPTIONS, RUNTIME_ENTRIES, renderGeneratedModule } from './build-runtimes.mjs'

test('runtime entries table registers the editor iframe bundle', () => {
  assert.equal(RUNTIME_ENTRIES.length >= 1, true)
  const editor = RUNTIME_ENTRIES.find((entry) => entry.id === 'editor-runtime')
  assert.ok(editor)
  assert.equal(editor.entry, 'packages/editor-runtime/runtime-src/index.ts')
  assert.equal(editor.outfile, 'packages/editor-runtime/runtime/generated/editor-runtime.source.ts')
  assert.equal(editor.exportName, 'EDITOR_RUNTIME_SOURCE')
})

test('esbuild options stay unminified IIFE for readable iframe source', () => {
  assert.equal(ESBUILD_OPTIONS.format, 'iife')
  assert.equal(ESBUILD_OPTIONS.target, 'es2017')
  assert.equal(ESBUILD_OPTIONS.minify, false)
  assert.equal(ESBUILD_OPTIONS.platform, 'browser')
  assert.equal(ESBUILD_OPTIONS.write, false)
})

test('renderGeneratedModule writes a typecheckable string export', async () => {
  const bundle = '(() => {\n  var x = 1;\n})();\n'
  const rendered = renderGeneratedModule('EDITOR_RUNTIME_SOURCE', bundle)
  assert.match(rendered, /^\/\/ Generated by scripts\/build-runtimes\.mjs/)
  assert.match(rendered, /export const EDITOR_RUNTIME_SOURCE = /)
  const dir = await mkdtemp(path.join(tmpdir(), 'ark-runtime-'))
  const file = path.join(dir, 'out.ts')
  await writeFile(file, rendered)
  const roundTrip = await readFile(file, 'utf8')
  assert.equal(roundTrip, rendered)
  const quoted = rendered.match(/export const EDITOR_RUNTIME_SOURCE = (".*")\n$/)
  assert.ok(quoted)
  assert.equal(JSON.parse(quoted[1]), bundle)
})
