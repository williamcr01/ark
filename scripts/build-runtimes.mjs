#!/usr/bin/env node

/**
 * Bundles iframe runtime TypeScript entries into committed string modules.
 *
 * Add a row to `RUNTIME_ENTRIES` to register another runtime (e.g. deck-preview).
 * Output is a TypeScript module exporting one string constant, so tsc/Vite/vitest
 * need no extra build step. Run `pnpm build:runtimes` after editing a runtime-src
 * tree; `pnpm build:runtimes:check` fails if the committed file is stale.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import * as esbuild from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** @typedef {{ id: string, entry: string, outfile: string, exportName: string }} RuntimeEntry */

/** Register each iframe runtime here. One object per bundle. */
export const RUNTIME_ENTRIES = [
  {
    id: 'editor-runtime',
    entry: 'packages/editor-runtime/runtime-src/index.ts',
    outfile: 'packages/editor-runtime/runtime/generated/editor-runtime.source.ts',
    exportName: 'EDITOR_RUNTIME_SOURCE',
  },
  {
    id: 'deck-handshake',
    entry: 'packages/deck-preview/runtime-src/handshake/index.ts',
    outfile: 'packages/deck-preview/runtime/generated/handshake.source.ts',
    exportName: 'DECK_HANDSHAKE_RUNTIME_SOURCE',
  },
  {
    id: 'deck-css-nav',
    entry: 'packages/deck-preview/runtime-src/css-nav/index.ts',
    outfile: 'packages/deck-preview/runtime/generated/css-nav.source.ts',
    exportName: 'DECK_CSS_NAV_RUNTIME_SOURCE',
  },
  {
    id: 'deck-custom-bridge',
    entry: 'packages/deck-preview/runtime-src/custom-bridge/index.ts',
    outfile: 'packages/deck-preview/runtime/generated/custom-bridge.source.ts',
    exportName: 'DECK_CUSTOM_BRIDGE_RUNTIME_SOURCE',
  },
  {
    id: 'deck-reveal-adapter',
    entry: 'packages/deck-preview/runtime-src/reveal-adapter/index.ts',
    outfile: 'packages/deck-preview/runtime/generated/reveal-adapter.source.ts',
    exportName: 'DECK_REVEAL_ADAPTER_RUNTIME_SOURCE',
  },
]

export const ESBUILD_OPTIONS = {
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2017',
  minify: false,
  sourcemap: false,
  legalComments: 'none',
  keepNames: true,
  treeShaking: true,
  write: false,
  logLevel: 'silent',
}

export function renderGeneratedModule(exportName, source) {
  return [
    '// Generated by scripts/build-runtimes.mjs. Do not edit.',
    `export const ${exportName} = ${JSON.stringify(source)}`,
    '',
  ].join('\n')
}

export async function bundleRuntimeEntry(entry, options = {}) {
  const result = await esbuild.build({
    ...ESBUILD_OPTIONS,
    absWorkingDir: options.root ?? root,
    entryPoints: [entry.entry],
  })

  const text = result.outputFiles?.[0]?.text
  if (typeof text !== 'string') {
    throw new Error(`esbuild produced no output for ${entry.id}`)
  }

  return text
}

export async function buildRuntimes({ checkOnly = false, repoRoot = root } = {}) {
  const stale = []

  for (const entry of RUNTIME_ENTRIES) {
    const source = await bundleRuntimeEntry(entry, { root: repoRoot })
    const rendered = renderGeneratedModule(entry.exportName, source)
    const outfile = path.join(repoRoot, entry.outfile)

    if (checkOnly) {
      let existing = ''
      try {
        existing = await readFile(outfile, 'utf8')
      } catch {
        console.error(`Runtime bundle missing at ${outfile}. Run pnpm build:runtimes.`)
        stale.push(entry.id)
        continue
      }

      if (existing !== rendered) {
        console.error(
          `Runtime bundle ${entry.id} is out of date. Run pnpm build:runtimes and commit the result.`,
        )
        stale.push(entry.id)
      }

      continue
    }

    await mkdir(path.dirname(outfile), { recursive: true })
    await writeFile(outfile, rendered, 'utf8')
    console.log(`Wrote ${outfile} (${source.length} bytes)`)
  }

  if (checkOnly) {
    if (stale.length) {
      return 1
    }

    console.log('Runtime bundles are up to date.')
  }

  return 0
}

const isMain =
  process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url

if (isMain) {
  const checkOnly = process.argv.includes('--check')
  buildRuntimes({ checkOnly })
    .then((code) => {
      process.exit(code)
    })
    .catch((error) => {
      console.error(error)
      process.exit(1)
    })
}
